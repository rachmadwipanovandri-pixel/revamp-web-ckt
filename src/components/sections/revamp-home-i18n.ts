/**
 * The static artifact contains real links, so they need the same locale
 * prefix as the surrounding Next navigation. Without this pass, a click from
 * /cn (or /jp, /kr) silently falls back to the Indonesian route.
 */
export function localizeRevampHomeRoutes(markup: string, locale: Locale) {
  let result = markup;
  const paths = [
    "/",
    "/marketing",
    "/chat",
    "/crm",
    "/features",
    "/integrations",
    "/industries",
    "/stories",
    "/pricing",
    "/solutions",
    "/blog",
    "/contact-us",
  ];

  for (const path of paths) {
    const localizedPath =
      locale === "id"
        ? (ID_PATHS[path] ?? path)
        : `/${locale}${path === "/" ? "" : path}`;
    result = result.replaceAll(`href="${path}"`, `href="${localizedPath}"`);
  }

  return result;
}

export function localizeRevampHomeMarkup(markup: string, locale: Locale) {
  const copy = {
    ...STATIC_HOME_COPY[locale],
    ...COPY[locale as Exclude<Locale, "en" | "id">],
    ...ADDITIONAL_COPY[locale],
    ...JOURNEY_COPY[locale],
  };
  let result = markup;
  const localizedPath = (path: string) =>
    locale === "id" ? path : `/${locale}${path}`;
  const blogNavLink = `<li class="mnav__item"><a class="mnav__link" href="${localizedPath("/blog")}">Blog</a></li>`;
  if (!/<a class="mnav__link" href="[^"]+">Blog<\/a>/.test(result)) {
    result = result.replace(
      /(<li class="mnav__item"><a class="mnav__link" href="[^"]+">Pricing<\/a><\/li>)/,
      `$1${blogNavLink}`,
    );
  }
  const contactHref = localizedPath("/contact-us");
  result = result
    .replaceAll(
      '<button class="btn btn--ghost" type="button" data-demo>Talk to sales</button>',
      `<a class="btn btn--ghost" href="${contactHref}">Talk to sales</a>`,
    )
    .replaceAll(
      '<button class="btn btn--soft" type="button" data-demo>Talk to sales</button>',
      `<a class="btn btn--soft" href="${contactHref}">Talk to sales</a>`,
    );
  if (Object.keys(copy).length === 0) return result;
  const productNames = [
    "Cekat Marketing",
    "Cekat Chat",
    "Cekat CRM",
    "Cekat Broadcasts",
    "Cekat Automation",
    "Cekat Analytics",
  ];
  // Replace complete phrases before shorter fragments. The hero's sr-only
  // label contains the full headline, while its visual version splits the
  // same words across nested spans.
  const entries = Object.entries(copy).sort(
    ([left], [right]) => right.length - left.length,
  );
  const protectedDataAttributes: Array<[string, string]> = [];
  result = result.replace(
    /\b(data-[\w:-]+=")([^"]*)(")/g,
    (_attribute, prefix: string, value: string, suffix: string) => {
      const token = `\uE000cekat-data-${protectedDataAttributes.length}\uE001`;
      protectedDataAttributes.push([token, value]);
      return `${prefix}${token}${suffix}`;
    },
  );
  const replaceCopy = (from: string, to: string) => {
    const variants = new Set([from, from.replaceAll("&", "&amp;")]);
    for (const variant of variants) {
      result = result.replaceAll(`>${variant}<`, `>${to}<`);
      result = result.replaceAll(`>${variant} `, `>${to} `);
      result = result.replaceAll(` ${variant}<`, ` ${to}<`);
      // The approved hero splits "... revenue technology" across nested spans.
      result = result.replaceAll(`>${variant}</span>`, `>${to}</span>`);
      result = result.replaceAll(` ${variant}</span>`, ` ${to}</span>`);
      // Accessible names and image descriptions are part of the localized UI too.
      result = result.replaceAll(`="${variant}"`, `="${to}"`);
    }
  };
  // Translate whole CTA phrases containing product names before shielding
  // those names from the shorter generic product/category translations.
  for (const [from, to] of entries) {
    if (productNames.some((name) => from.includes(name))) {
      replaceCopy(from, to);
    }
  }
  const protectedProductNames = productNames.map((name, index) => {
    const token = `\uE000cekat-product-${index}\uE001`;
    result = result.replaceAll(name, token);
    return [token, name] as const;
  });
  for (const [from, to] of entries) {
    if (!productNames.some((name) => from.includes(name))) {
      replaceCopy(from, to);
    }
  }
  for (const [token, name] of protectedProductNames) {
    result = result.replaceAll(token, name);
  }
  for (const [token, value] of protectedDataAttributes) {
    result = result.replaceAll(token, value);
  }
  return result;
}
